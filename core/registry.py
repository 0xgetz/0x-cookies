"""Platform registry shared by the cookie-checker and the OpenBullet configs.

Dependency-free (no Playwright): describes, per platform, the protected probe
URL and the valid/invalid rules. Run `python gen_configs.py` to turn it into
`configs/platforms/*.json`.
"""
from __future__ import annotations

from dataclasses import dataclass, field



# --------------------------------------------------------------------------- #
# Platform registry
# --------------------------------------------------------------------------- #
@dataclass
class Platform:
    name: str
    url: str                              # login-protected probe URL
    valid_url_re: str                     # final URL matches => authenticated
    invalid_url_re: str                   # final URL matches => bounced to login
    # cookies that identify this platform
    detect_domains: list[str] = field(default_factory=list)
    detect_names: list[str] = field(default_factory=list)
    # an auth cookie that must exist for the file to be worth probing
    required_any: list[str] = field(default_factory=list)
    # body markers
    valid_body_any: list[str] = field(default_factory=list)
    invalid_body_any: list[str] = field(default_factory=list)
    # logged-in-only DOM selectors (proves a live session for SPA sites that
    # neither redirect nor change title)
    valid_selector_any: list[str] = field(default_factory=list)
    # login/sign-up-only DOM selectors (proves a logged-out session)
    invalid_selector_any: list[str] = field(default_factory=list)
    # redirect-based platforms are the most reliable; marker-based are best-effort
    mode: str = "redirect"                # "redirect" | "marker"


def _p(name, url, valid_re, invalid_re, domains, names, required, **kw) -> Platform:
    return Platform(name=name, url=url, valid_url_re=valid_re, invalid_url_re=invalid_re,
                    detect_domains=domains, detect_names=names, required_any=required, **kw)


